import { BONUS_ROOMS, DAILY_ROOMS } from '../src/game/daily/catalog';
import { dailyIndex, dailyRoomFor } from '../src/game/daily/daily';
import { solutionKey, withReferenceEcho } from '../src/game/echo';
import { movesAllowed, replay } from '../src/game/engine';
import { allVariantRooms, INTERLUDES } from '../src/game/observer/rooms';
import { CAMPAIGN, CAMPAIGN_SIZE, CHAPTERS, ROOMS_PER_CHAPTER, chapterOf, getRoom, getRoomById, roomId } from '../src/game/levels';
import SOLUTIONS from '../src/game/levels/solutions.generated.json';
import { decodeSolution } from '../src/game/solver/solver';
import { SECONDS_PER_TURN, TIMER_GRACE_SECONDS, validateStructure } from '../src/game/validator';

const stored = SOLUTIONS as Record<string, string>;
const ALL = [...CAMPAIGN, ...DAILY_ROOMS, ...BONUS_ROOMS];
// Interludes and room-memory variants, as the solver sees them (echo rooms with their reference echo).
const EXTRA = [...INTERLUDES.map((i) => i.room), ...allVariantRooms(getRoomById)].map(withReferenceEcho);
const SOLVED = [...ALL, ...EXTRA];

describe('campaign catalog', () => {
  test('has exactly 100 rooms in 10 chapters of 10', () => {
    expect(CAMPAIGN_SIZE).toBe(100);
    expect(CHAPTERS).toHaveLength(10);
    for (const c of CHAPTERS) {
      const rooms = CAMPAIGN.filter((r) => r.chapter === c.number);
      expect(rooms).toHaveLength(ROOMS_PER_CHAPTER);
      expect(rooms[0].index).toBe(c.firstRoom);
    }
  });

  test('ids, indexes and names are unique and sequential', () => {
    CAMPAIGN.forEach((r, i) => {
      expect(r.index).toBe(i + 1);
      expect(r.id).toBe(roomId(i + 1));
      expect(getRoom(i + 1)).toBe(r);
      expect(chapterOf(i + 1)?.number).toBe(r.chapter);
    });
    expect(new Set(CAMPAIGN.map((r) => r.name)).size).toBe(100);
    expect(new Set(ALL.map((r) => r.id)).size).toBe(ALL.length);
  });

  test('no two rooms share an identical layout', () => {
    const sig = ALL.map((r) => JSON.stringify([r.width, r.tiles, r.start, r.items, r.blocks]));
    expect(new Set(sig).size).toBe(ALL.length);
  });

  test.each(SOLVED.map((r) => [solutionKey(r), r] as const))('%s passes structural validation', (_id, r) => {
    expect(validateStructure(r)).toEqual([]);
  });
});

describe('stored solutions (generated by the solver)', () => {
  test('every room has a stored solution', () => {
    for (const r of SOLVED) expect(typeof stored[solutionKey(r)]).toBe('string');
  });

  test('no stored solution belongs to a room that no longer exists', () => {
    const keys = new Set(SOLVED.map(solutionKey));
    expect(Object.keys(stored).filter((k) => !keys.has(k))).toEqual([]);
  });

  test.each(SOLVED.map((r) => [solutionKey(r), r] as const))('%s: stored solution wins within its limits', (_id, r) => {
    const actions = decodeSolution(stored[solutionKey(r)]);
    const end = replay(r, actions);
    expect(end.status).toBe('won');
    expect(end.moves).toBe(actions.length);
    if (r.moveLimit !== undefined) expect(actions.length).toBeLessThanOrEqual(movesAllowed(r, end));
    if (r.timeLimit !== undefined) {
      expect(r.timeLimit).toBeGreaterThanOrEqual(Math.ceil(actions.length * SECONDS_PER_TURN + TIMER_GRACE_SECONDS));
    }
  });
});

describe('daily challenge selection', () => {
  test('is deterministic per day', () => {
    expect(dailyRoomFor('2026-10-14').id).toBe(dailyRoomFor('2026-10-14').id);
  });

  test('never repeats on consecutive days and covers the whole pool each cycle', () => {
    const start = new Date(Date.UTC(2026, 0, 1));
    let prev = -1;
    const seen = new Map<number, number>();
    for (let d = 0; d < 365 * 3; d++) {
      const day = new Date(start.getTime() + d * 86_400_000).toISOString().slice(0, 10);
      const i = dailyIndex(day);
      expect(i).toBeGreaterThanOrEqual(0);
      expect(i).toBeLessThan(DAILY_ROOMS.length);
      expect(i).not.toBe(prev);
      prev = i;
      seen.set(i, (seen.get(i) ?? 0) + 1);
    }
    expect(seen.size).toBe(DAILY_ROOMS.length);
  });
});
