#!/usr/bin/env python3
"""Paints the backdrop behind the board for every environment (src/game/environments.ts).

Same Google Cloud setup as scripts/make-scenes.py (GOOGLE_TTS_SA_JSON, Vertex AI on, Agent
Platform User role); never commit the key. The board covers the middle of the screen, so each
backdrop is an empty, wide interior: the place itself, readable around the board's edges.

Usage:
    python3 scripts/make-backdrops.py [--only ENV ...] [--force]

Output: assets/backdrops/<env>.jpg (576x1024), assets/backdrops/manifest.json and
src/services/story/backdrops.generated.ts.
"""
import argparse
import importlib.util
import io
import json
import os
import subprocess
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets", "backdrops")
MANIFEST = os.path.join(OUT, "manifest.json")
TS_OUT = os.path.join(ROOT, "src", "services", "story", "backdrops.generated.ts")

STYLE = (
    "Stylised cinematic 3D environment art for a colourful mobile adventure game for teenagers, like a polished animated film. "
    "Wide interior view of the empty location from a high angle, vertical 9:16. Rich saturated accent colours, expressive lighting, "
    "clear shapes, believable architecture with details like door frames, vents, cables, signage and wear. "
    "The middle of the image is an open, uncluttered floor area. No people, no robots, no characters, no text, no captions, no logos, no watermark. "
    "Part of the Meridian Vault, an abandoned underground research facility."
)

_spec = importlib.util.spec_from_file_location("make_scenes", os.path.join(ROOT, "scripts", "make-scenes.py"))
_ms = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_ms)
_ms.prompt_for = lambda s: f"{s['shot']}.\n\n{STYLE}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    if not os.environ.get("GOOGLE_TTS_SA_JSON"):
        sys.exit("Set GOOGLE_TTS_SA_JSON.")
    os.makedirs(OUT, exist_ok=True)
    manifest = json.load(open(MANIFEST)) if os.path.exists(MANIFEST) else {}
    envs = json.loads(subprocess.run(["npx", "tsx", "scripts/backdrop-list.ts"], cwd=ROOT, check=True, capture_output=True, text=True).stdout)
    wanted = {e["key"] for e in envs}
    for i, e in enumerate(envs):
        spec = {"model": _ms.MODEL, "prompt": _ms.prompt_for(e)}
        path = os.path.join(OUT, f"{e['key']}.jpg")
        if args.only and e["key"] not in args.only:
            continue
        if not args.force and manifest.get(e["key"]) == spec and os.path.exists(path):
            continue
        for _ in range(3):
            im = Image.open(io.BytesIO(_ms.paint(e))).convert("RGB")
            if _ms.letterbox(im)[0] < 24:
                break
            print(f"  {e['key']} came back letterboxed, repainting", flush=True)
        else:
            im = _ms.fill_frame(im)
        im = im.resize((576, 1024), Image.LANCZOS)
        im.save(path, "JPEG", quality=78, optimize=True, progressive=True)
        manifest[e["key"]] = spec
        with open(MANIFEST, "w") as fh:
            json.dump(manifest, fh, indent=1, sort_keys=True)
            fh.write("\n")
        print(f"[{i + 1}/{len(envs)}] {e['key']} {os.path.getsize(path) // 1024} KB", flush=True)
    keys = sorted(k for k in wanted if os.path.exists(os.path.join(OUT, f"{k}.jpg")))
    with open(TS_OUT, "w") as fh:
        fh.write("// Generated by scripts/make-backdrops.py. Do not edit.\n")
        fh.write("/* eslint-disable @typescript-eslint/no-require-imports */\n")
        fh.write("export const BACKDROPS: Record<string, number> = {\n")
        for k in keys:
            fh.write(f"  '{k}': require('../../../assets/backdrops/{k}.jpg'),\n")
        fh.write("};\n")
    print(f"total {len(keys)} of {len(wanted)}")


if __name__ == "__main__":
    main()
